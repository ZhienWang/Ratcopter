local function loadKeyBindings()
  local path = system.pathForFile("keybinds.txt", system.DocumentsDirectory)
  local file = path and io.open(path, "r")
  if file then
    for line in file:lines() do
      local key, value = line:match("^(%a+)=([%w]+)$")
      if key and keyBindings[key] ~= nil then
        keyBindings[key] = value
      elseif key == "holdToDash" then
        holdToDashEnabled = (value == "true")
      elseif key == "holdDashDelayMs" then
        local ms = tonumber(value)
        if ms then
          holdDashDelayMs = math.max(HOLD_DASH_DELAY_MIN_MS, math.min(HOLD_DASH_DELAY_MAX_MS, ms))
        end
      end
    end
    io.close(file)
  end
