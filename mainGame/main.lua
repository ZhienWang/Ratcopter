-- ---------- Round bookkeeping ----------
-- Finalizes the round: totals both lanes' scores as they stand at the moment
-- of the crash and moves on to the round/match summary. Under the
-- elimination rule this is called from exactly one place -- the tick on
-- which either bird goes down -- rather than from a spectate/skip path.
finishRound = function()
  match.playerTotal = match.playerTotal + playerLane.score
  match.aiTotal = match.aiTotal + aiLane.score

  -- Both can go down on the same tick: the AI's handicap roll fires while
  -- updateLane is scoring its pipe, which is the same tick the player may
  -- hit something, so "both" is a real outcome and not just a tidy default.
  if not playerLane.alive and not aiLane.alive then
    match.eliminated = "both"
  elseif not playerLane.alive then
    match.eliminated = "you"
  else
    match.eliminated = "ai"
  end

  if match.round >= TOTAL_ROUNDS then
    match.phase = "matchover"
    if match.playerTotal > match.bestTotal then
      match.bestTotal = match.playerTotal
      saveBestTotal()
      bestLabel.text = "BEST " .. match.bestTotal
    end
  else
    match.phase = "roundover"
  end
  refreshOverlay()
end

-- ---------- Main loop ----------
local function gameLoop()
  if menuOpen then return end -- freeze the action while the keybind menu is open
  -- Nothing ticks outside a live round: the payoff/flight pass below is part
  -- of the action too, so it stops with the rest of it rather than bouncing
  -- coins across a finished round's overlay and dropping pipes into two
  -- frozen lanes. Whatever is still queued is destroyed by
  -- clearPendingPipeSpawns when the next round starts.
  if match.phase ~= "playing" then return end

  roundElapsed = roundElapsed + TICK_DT

  nextDotSpawnIn = nextDotSpawnIn - TICK_DT
  if nextDotSpawnIn <= 0 then
    nextDotSpawnIn = rollNextDotSpawnIn()
    local targetLane = (math.random() < 0.5) and playerLane or aiLane
    if targetLane.alive then
      spawnDot(targetLane)
    end
  end

  local dashWasOnCooldown = playerLane.dashCooldownRemaining > 0
  updateLane(playerLane, TICK_DT)
  if dashWasOnCooldown and playerLane.dashCooldownRemaining <= 0 then
    blinkDashIndicator()
  end

  if aiLane.alive then
    updateAI(aiLane, TICK_DT)
  end
  updateLane(aiLane, TICK_DT)

  -- Elimination: the first crash ends the round for BOTH lanes. Leaving
  -- "playing" is what stops them -- nothing calls updateLane outside this
  -- branch any more -- so the survivor freezes exactly where it was
  -- instead of flying on alone.
  if not playerLane.alive or not aiLane.alive then
    finishRound()
    return
  end

  -- Delayed coin payoffs: the collected coin bounces across to the opposing
  -- lane over COIN_PIPE_DELAY, and the pipe is generated at the moment it
  -- lands. Walked back-to-front so a payoff can be dropped as it fires.
  for i = #pendingPipeSpawns, 1, -1 do
    local pending = pendingPipeSpawns[i]
    if not pending.flight then
      beginCoinFlight(pending) -- first tick this payoff has been seen
    end
    pending.remaining = pending.remaining - TICK_DT
    updateCoinFlight(pending.flight, 1 - math.max(0, pending.remaining) / COIN_PIPE_DELAY)
    if pending.remaining <= 0 then
      endCoinFlight(pending)
      spawnPipe(otherLane(pending.from))
      table.remove(pendingPipeSpawns, i)
    end
  end
end

local gameLoopTimer = timer.performWithDelay(25, gameLoop, 0)

end -- main()

-- The layout is built exactly once, from display.actualContentWidth/Height,
-- and nothing repositions afterwards -- so those have to be the *settled*
-- values. Deferring one frame (what this used to do) is enough on desktop,
-- but not in a mobile browser: the canvas there was measured stepping
-- 300x150 -> 412x618 -> 412x880 across the first second, and laying out
-- against the middle reading puts the real left edge ~86px inside where the
-- game thinks it is. The lanes still look about right, but everything
-- anchored to SCREEN_LEFT -- the BEST label, and the dash control -- slides
-- off the screen, which is what made the dash unreachable on a phone.
--
-- So poll until the size stops changing before building anything, with a
-- hard cap so a pathological resize loop can still boot the game.
local LAYOUT_POLL_MS = 50
local LAYOUT_STABLE_SAMPLES = 3 -- consecutive identical readings
-- Stability alone isn't enough: the canvas sits at its 300x150 default for
-- the first few hundred milliseconds, which reads as perfectly stable and
-- would boot the layout against the placeholder -- the very thing this is
-- meant to avoid. So don't accept any reading before this floor.
local LAYOUT_MIN_WAIT_MS = 400
local LAYOUT_MAX_WAIT_MS = 3000

local lastW, lastH, stableCount, waited = nil, nil, 0, 0
local layoutWaitTimer
layoutWaitTimer = timer.performWithDelay(LAYOUT_POLL_MS, function()
  local w, h = display.actualContentWidth, display.actualContentHeight
  if w == lastW and h == lastH then
    stableCount = stableCount + 1
  else
    stableCount, lastW, lastH = 0, w, h
  end
  waited = waited + LAYOUT_POLL_MS

  local settled = stableCount >= LAYOUT_STABLE_SAMPLES and waited >= LAYOUT_MIN_WAIT_MS
  if settled or waited >= LAYOUT_MAX_WAIT_MS then
    timer.cancel(layoutWaitTimer)
    main()
  end
end, 0)
