    land = nil,
    landSimX = LANE_W,
    scoreText = nil,
    label = nil,
    alive = false,
    score = 0,
    velocityY = 0,
    aiCooldown = 0,
    aiDelayQueue = {},
    aiBobPhase = 0,
    dashCooldownRemaining = 0,
    dashRemaining = 0,
  }
end

local function buildLaneVisuals(lane)
  local g = lane.group
  local flip = lane.isAI and -1 or 1

  lane.background = display.newImageRect(g, getCurrentTheme().background, LANE_W, LANE_H)
  lane.background.x = laneDisplayX(lane, LANE_W / 2)
  lane.background.y = LANE_H / 2
  lane.background.xScale = flip

  local landH = LANE_H * LAND_HEIGHT_FRACTION
  lane.land = display.newImageRect(g, getCurrentTheme().land, LANE_W * 2, landH)
  lane.land.x = laneDisplayX(lane, lane.landSimX)
  lane.land.y = LANE_H - landH / 2
  lane.land.xScale = flip

  -- The lane starts with no pipes at all -- they're created on demand by
  -- spawnPipe as the other lane earns them. They go into their own group,
  -- created here between the land and the bird purely for z-order: dropping
  -- each new pipe straight into `g` would stack it above the bird and the
  -- score text (both built below) instead of behind them.
  lane.pipeGroup = display.newGroup()
  g:insert(lane.pipeGroup)

  -- Coins need the same treatment for the same reason: spawned straight into
  -- `g` they landed on top of the bird, the score and the lane label (a coin
  -- can sit as high as CEIL_LIMIT, which is level with the score readout).
  -- Their own group, inserted after the pipes', keeps them above the pipes
  -- and behind everything built below.
  lane.dotGroup = display.newGroup()
  g:insert(lane.dotGroup)

  -- the AI flies a whitened recolor of the same sprite sheet (a plain
  -- grayscale tint reads as pale gray, not white, since the fur's mid-tones
  -- never reach anywhere near 255 -- see make_bird_white.py) and, unlike
  -- the rest of its lane's art, is NOT flipped: it faces right, same as
  -- the player, rather than mirroring the flipped background/pipes
  local birdImage = lane.isAI and "Assets/bird_white.png" or "Assets/bird.png"
  local sheet = graphics.newImageSheet(birdImage, {
    width = 280, height = 200, numFrames = 4,
    sheetContentWidth = 1120, sheetContentHeight = 200,
  })
  local seq = { name = "walking", start = 1, count = 3, time = 300, loopCount = 2, loopDirection = "forward" }
  lane.bird = display.newSprite(g, sheet, seq)
  lane.bird.xScale = 0.25 * LANE_SCALE
  lane.bird.yScale = 0.25 * LANE_SCALE
  lane.bird.x = laneDisplayX(lane, BIRD_LOCAL_X)
  lane.bird.y = LANE_H * 0.42

  -- text is never flipped -- it's positioned identically in both lanes
  -- (LANE_W/2, i.e. each lane's own center) and always renders normally
  lane.scoreText = display.newText({ text = "0", x = 0, y = 0, font = "Assets/troika.otf", fontSize = 36 })
  g:insert(lane.scoreText)
  lane.scoreText.x = laneDisplayX(lane, LANE_W / 2)
  lane.scoreText.y = 50
  lane.scoreText:setFillColor(1, 1, 1)

  lane.label = display.newText({ text = lane.isAI and "AI" or "YOU", x = 0, y = 0, font = "Assets/troika.otf", fontSize = 20 })
  g:insert(lane.label)
  lane.label.x = laneDisplayX(lane, LANE_W / 2)
  lane.label.y = 88
  lane.label:setFillColor(1, 1, 1)
end

local function applyThemeToLane(lane)
  lane.background.fill = { type = "image", filename = getCurrentTheme().background }
  lane.land.fill = { type = "image", filename = getCurrentTheme().land }
  -- re-skin whatever pipes this lane happens to be holding at the moment;
  -- the two lanes no longer carry the same pipes, so each re-rolls its own
  for _, p in ipairs(lane.pipes) do
    p.skin = randomPipeSkin()
    local jaw = jawImage(p.skin, p.shape) -- the shape survives a theme swap
    if p.topJaw then p.topJaw.fill = { type = "image", filename = jaw } end
    if p.botJaw then p.botJaw.fill = { type = "image", filename = jaw } end
    if p.groundImg then
      p.groundImg.fill = { type = "image", filename = GROUND.image(p.ground, p.groundSize, getCurrentTheme().key) }
    end
  end
end

local function resetLane(lane)
  lane.alive = true
  lane.score = 0
  lane.scoreText.text = "0"
  lane.velocityY = FLAP_VY * 0.6
  lane.bird.y = LANE_H * 0.42
  lane.bird.rotation = 0
  lane.bird.alpha = 1
  lane.aiCooldown = 0

  -- pre-fill so the FIFO immediately has AI_DELAY_TICKS entries; without
  -- this the queue would start empty and the first few ticks would have
  -- zero delay (insert-then-remove only holds a fixed backlog once it's
  -- already at that size)
  lane.aiDelayQueue = {}
  for _ = 1, AI_DELAY_TICKS do
    lane.aiDelayQueue[#lane.aiDelayQueue + 1] = 0
  end
  lane.aiBobPhase = math.random() * 6.28
  lane.aiLastTarget, lane.aiLastAimY = nil, 0 -- updateAI's drift feed-forward

  lane.dashCooldownRemaining = 0
  lane.dashRemaining = 0

  for _, d in ipairs(lane.dots) do
    d.display:removeSelf()
  end
  lane.dots = {}

  lane.landSimX = LANE_W

  -- every round opens on a completely clear lane: the first pipe only shows
  -- up once the other lane's bird has collected a coin
  for _, p in ipairs(lane.pipes) do
    p:removeSelf()
  end
  lane.pipes = {}
  lane.pipesUntilWideGap = rollPipesUntilWideGap()
end

-- Puts a pipe's two jaw images either side of its opening. Called once when
-- the pipe is built and again on every tick a clamp closes a little further.
-- A jaw image carries JAW.notch of shaped tip below the row that represents a
-- flat edge, so the image sits that much lower than its own half-height.
local function layoutPipeJaws(pipe)
  local edge = JAW.h / 2 - JAW.notch
  if pipe.topJaw then pipe.topJaw.y = -pipe.gapHalf - edge end
  if pipe.botJaw then pipe.botJaw.y = pipe.gapHalf + edge end
end

-- Where the AI should aim at this column, and how much room it has there.
-- For a two-jaw column that is the middle of the gap, tightest point first.
-- A one-jaw column has no middle -- the open lane runs from its single edge
-- out to the ceiling or the floor -- so it aims at the middle of that open
-- lane instead. Worked out fresh on every call rather than stored at spawn,
-- since a drifting column carries its edge up and down with it.
local function pipeAim(pipe)
  if pipe.hasTop and pipe.hasBot then
    return pipe.y, pipe.gapHalf - shapeNotchPx(pipe.shape, 0)
  end
  if pipe.hasTop then
    local edgeY = pipe.y - pipe.gapHalf
    return (edgeY + GROUND_LIMIT) / 2, (GROUND_LIMIT - edgeY) / 2
  end
  local edgeY = pipe.y + pipe.gapHalf
  return (CEIL_LIMIT + edgeY) / 2, (edgeY - CEIL_LIMIT) / 2
end

-- Half the opening at `atX`, in lane coordinates: the pipe's current opening
-- (which a clamp shrinks over time) minus however far its tip bites in at
-- that point across. This is the one place the shape turns into something
-- that can kill you, and it is the same profile the art was drawn from.
local function pipeGapHalfAt(pipe, atX)
  local u = (atX - pipe.simX) / (PIPE_HALF_W * JAW.artHalf)
  return pipe.gapHalf - shapeNotchPx(pipe.shape, u)
end

local function laneCollides(lane, pipe)
  if BIRD_LOCAL_X > pipe.simX - PIPE_HALF_W and BIRD_LOCAL_X < pipe.simX + PIPE_HALF_W then
    local half = pipeGapHalfAt(pipe, BIRD_LOCAL_X)
    -- Only the jaws this column actually has can hit you: a ceiling-only
    -- column leaves the whole lane below it open, and vice versa.
    if pipe.hasTop and lane.bird.y < pipe.y - half then return true end
    if pipe.hasBot and not pipe.ground and lane.bird.y > pipe.y + half then return true end
  end
  -- A ground obstacle is far wider than the pipe above it, so it is tested
  -- across its own width against its own outline.
  if pipe.ground then
    local surface = GROUND.surfaceAt(pipe.ground, pipe.groundSize, BIRD_LOCAL_X - pipe.simX)
    if surface and lane.bird.y > surface then return true end
  end
  return false
end

-- Clearance kept between a coin and a pipe, so neither rides in on top of
-- (or visually touching) the other -- half a pipe's width plus the coin's
-- own full size. Pipes and coins are placed by independent spawners now,
-- rather than coins being slotted into a course the pipes already defined,
-- so each has to be nudged clear of the other explicitly.
local COIN_PIPE_CLEARANCE = PIPE_HALF_W + DOT_SIZE

-- Slides `simX` right until it clears every entry of the lists passed after
-- it (any lists of things carrying a .simX) by COIN_PIPE_CLEARANCE. Walking
-- them in ascending order means one pass settles it: each push can only move
-- simX further right, i.e. toward entries not yet checked. Takes several
-- lists because a spot usually has to clear both kinds of object at once,
-- and clearing them one list at a time could undo the previous pass.
local function pushClearOf(simX, ...)
  local xs = {}
  for _, list in ipairs({ ... }) do
    for _, o in ipairs(list) do
      xs[#xs + 1] = o.simX
    end
  end
  table.sort(xs)
  for _, x in ipairs(xs) do
    if math.abs(x - simX) < COIN_PIPE_CLEARANCE then
      simX = x + COIN_PIPE_CLEARANCE
    end
  end
  return simX
end

-- True when nothing in `others` sits within COIN_PIPE_CLEARANCE of `simX`.
-- Used where a spot has to be accepted or rejected as-is rather than nudged:
-- pushing a between-the-pipes coin to the right would shove it through the
-- pipe the midpoint was measured from.
local function isClearOf(simX, others)
  for _, o in ipairs(others) do
    if math.abs(o.simX - simX) < COIN_PIPE_CLEARANCE then
      return false
    end
  end
  return true
end

-- Generates one pipe in `lane`, riding in from off-screen right exactly the
-- way course pipes used to. Called only by the delayed coin payoff in
-- gameLoop -- nothing spawns pipes on a timer. The spacing rules are kept
-- by placing it a full nextPipeSpacing() behind the lane's current
-- rightmost pipe whenever that already sits further out than the normal
-- spawn point, so a lane fed a burst of coins gets its pipes queued up at
-- proper spacing instead of stacked on top of each other.
local function spawnPipe(lane)
  -- A pipe is a group holding two jaws, not a single image: the opening
  -- between them is set at runtime rather than baked into the picture, which
  -- is what lets a clamp close. The group's own y doubles as the centre of
  -- the opening, exactly as the old image's y did, so everything that reads
  -- p.y (the AI's target, coin placement) is unchanged.
  local p = display.newGroup()
  lane.pipeGroup:insert(p)
  p.scored = false
  p.skin = randomPipeSkin()

  -- How far this column's opening reaches from p.y out to a jaw edge. The
  -- ramp widens it while two-jaw columns are still being introduced and
  -- closes it down again past ramp_tighten_at.
  p.gapHalf = GAP_HALF_H * rampGapScale()
  p.gapHalfBase = p.gapHalf
  p.clampT = 0

  p.hasTop = true
  p.hasBot = true
  if math.random() >= twoJawChance() then
    -- Early in the round a column carries one jaw only, and the whole lane
    -- past its edge is open to fly through.
    if math.random() < 0.5 then p.hasBot = false else p.hasTop = false end
  end

  -- Only a two-jaw column can clamp: there has to be something on both
  -- sides for the opening to squeeze shut between.
  p.clamping = p.hasTop and p.hasBot and math.random() < CLAMP.chance
  -- A breather needs both jaws for the same reason, and is only rolled for a
  -- column the clamp roll passed over, so the two never stack.
  p.breathing = p.hasTop and p.hasBot and not p.clamping
    and math.random() < BREATHE.chance * RAMP.unlocked("breathe")
  p.breathT = 0

  -- The bottom half may be a pyramid or a hump standing on the ground. The
  -- pipe above one keeps a flat tip: a shaped tip biting down on top of an
  -- obstacle reaching up would narrow the same opening from both sides.
  if p.hasBot and not p.clamping and not p.breathing and math.random() < GROUND.chance then
    p.ground = GROUND.kinds[math.random(#GROUND.kinds)]
    local sizes = p.ground == "pyramid" and #GROUND.pyramid.rows or #GROUND.humps
    p.groundSize = math.random(sizes)
    p.gapHalf = p.gapHalf * GROUND.open[p.ground]
    p.gapHalfBase = p.gapHalf
  end

  p.shape = "straight"
  if not p.clamping and not p.breathing and not p.ground and math.random() < SHAPES.chance then
    -- index 1 is "straight", so roll across the shaped ones only. A shape
    -- that is still being phased in (see RAMP.unlocks) is weighted by how
    -- far in it is: teeth at half-unlocked are half as likely as any other
    -- shape, and at nothing the roll falls to the rest.
    local total = 0
    for i = 2, #SHAPES.list do total = total + RAMP.unlocked(SHAPES.list[i]) end
    local r = math.random() * total
    for i = 2, #SHAPES.list do
      local w = RAMP.unlocked(SHAPES.list[i])
      if w > 0 then
        p.shape = SHAPES.list[i]
        if r < w then break end
        r = r - w
      end
    end
  end

  -- Any column whose opening keeps its size may drift, shaped or not, one
  -- jaw or two. Starts at a random point in its swing so a run of drifters
  -- is not a row of pipes moving in lockstep.
  p.drifting = DRIFT.amp > 0 and not p.clamping and not p.breathing and not p.ground
    and math.random() < DRIFT.chance * RAMP.unlocked("drift")
  p.driftPhase = math.random() * 2 * math.pi

  if p.ground then
    -- Nothing to choose: the obstacle stands on the ground, so its peak is
    -- fixed by its height, and the opening sits directly on top of it. p.y
    -- is still the centre of the opening, so pipeAim needs no special case
    -- -- for a one-piece column its "edge" is simply the peak.
    local h = GROUND.dims(p.ground, p.groundSize)
    p.y = GROUND.baseY - h - p.gapHalf
  elseif p.hasTop and p.hasBot then
    p.y = randomGapY()
  else
    -- Place the single jaw by its EDGE rather than by a gap centre, so the
    -- lane it leaves open is a known size instead of whatever randomGapY
    -- happens to give once the ramp has scaled the opening. RAMP.singleOpenMin
    -- is the least it ever leaves.
    local lo, hi, edgeY
    if p.hasTop then
      lo, hi = CEIL_LIMIT + 60, GROUND_LIMIT - RAMP.singleOpenMin
      edgeY = math.random(math.floor(lo), math.floor(math.max(lo, hi)))
      p.y = edgeY + p.gapHalf
    else
      lo, hi = CEIL_LIMIT + RAMP.singleOpenMin, GROUND_LIMIT - 60
      edgeY = math.random(math.floor(math.min(lo, hi)), math.floor(hi))
      p.y = edgeY - p.gapHalf
    end
  end
  -- The drift swings about wherever the column was placed; p.y itself is
  -- what moves, so everything that reads it follows along.
  p.driftBaseY = p.y
  if p.drifting then
    p.y = p.driftBaseY + math.sin(p.driftPhase) * DRIFT.amp
  end

  local jaw = jawImage(p.skin, p.shape)
  if p.hasTop then
    p.topJaw = display.newImageRect(p, jaw, PIPE_HALF_W * 2, JAW.h)
  end
  if p.hasBot and not p.ground then
    p.botJaw = display.newImageRect(p, jaw, PIPE_HALF_W * 2, JAW.h)
    p.botJaw.yScale = -1 -- the bottom jaw is the same art stood on its head
  end
  layoutPipeJaws(p)

  -- How far the column reaches either side of its centre -- a pipe's
  -- half-width, or an obstacle's if it is wider. Spawning, spacing and
  -- clean-up all measure off this rather than off PIPE_HALF_W, or a wide
  -- obstacle would pop into view already half on screen and vanish while
  -- half of it was still showing.
  p.halfW = PIPE_HALF_W
  if p.ground then
    local h, w = GROUND.dims(p.ground, p.groundSize)
    p.groundImg = display.newImageRect(p, GROUND.image(p.ground, p.groundSize, getCurrentTheme().key), w, h)
    -- the group sits at p.y, the obstacle's feet at GROUND.baseY
    p.groundImg.y = GROUND.baseY - h / 2 - p.y
    p.halfW = math.max(PIPE_HALF_W, w / 2)
  end

  -- Placed last, now that its width is known. The spacing rule is between
  -- the EDGES of neighbouring columns rather than their centres, so two wide
  -- obstacles in a row keep the same clear run between them as two pipes.
  local simX = math.max(PIPE_SPAWN_X, LANE_W + p.halfW)
  local rightmost = nil
  for _, q in ipairs(lane.pipes) do
    if (not rightmost) or q.simX > rightmost.simX then rightmost = q end
  end
  -- rolled on every spawn, as it always was: it also advances the counter
  -- behind the occasional widened gap
  local spacing = nextPipeSpacing(lane)
  if rightmost then
    spacing = spacing + (rightmost.halfW - PIPE_HALF_W) + (p.halfW - PIPE_HALF_W)
    simX = math.max(simX, rightmost.simX + spacing)
  end
  simX = pushClearOf(simX, lane.dots)
  p.simX = simX

  p.xScale = lane.isAI and -1 or 1
  p.x = laneDisplayX(lane, simX)
  lane.pipes[#lane.pipes + 1] = p
end

-- Spawns one coin into `lane`. The preferred spot is the midpoint of an
-- open gap between two of the lane's pipes that's still ahead of the bird:
-- since PIPE_SPACING is much wider than a pipe's own PIPE_HALF_W, a
-- midpoint is clear of both regardless of y, instead of landing on top of
-- one or too close to be grabbable. Requiring the gap to be ahead of the
-- bird keeps a coin from appearing behind it, already uncatchable. A lane
-- now routinely holds fewer than two pipes (they only exist while the other
-- lane is collecting coins), so with no such gap available the coin simply
-- rides in from the usual off-screen spawn point instead, pushed clear of
-- anything already out there.
local function spawnDot(lane)
  local pipesByX = {}
  for _, p in ipairs(lane.pipes) do
    pipesByX[#pipesByX + 1] = p
  end
  table.sort(pipesByX, function(a, b) return a.simX < b.simX end)

  local candidates = {}
  for i = 1, #pipesByX - 1 do
    local a, b = pipesByX[i], pipesByX[i + 1]
    local midX = (a.simX + b.simX) / 2
    -- ...and clear of any coin already sitting there. Without this a coin
    -- riding in from off-screen and a later coin placed at a midpoint could
    -- land on exactly the same spot -- two coins drawn as one, both
    -- collected by a single pass, sending two pipes for one visible pickup.
    if midX > BIRD_LOCAL_X + 40 and isClearOf(midX, lane.dots) then
      candidates[#candidates + 1] = { a = a, b = b, simX = midX }
    end
  end

  local simX, y
  if #candidates > 0 then
    local pick = candidates[math.random(#candidates)]
    simX = pick.simX
    local aimA = pipeAim(pick.a)
    local aimB = pipeAim(pick.b)
    y = (aimA + aimB) / 2 + math.random(-20, 20)
  else
    simX = pushClearOf(PIPE_SPAWN_X, lane.pipes, lane.dots)
    y = randomGapY() + math.random(-20, 20)
  end
  -- Clamped to the ground's surface (LAND_TOP), not GROUND_LIMIT -- that's
  -- the deeper death line the bird can sink into, and a coin spawned that
  -- low would visually land inside the dirt. The coin is drawn from its
  -- centre, so the limit is half a coin above the surface: clamping the
  -- centre to LAND_TOP itself still buried the bottom half of it.
  y = math.max(CEIL_LIMIT, math.min(LAND_TOP - DOT_SIZE / 2, y))

  local img = display.newImageRect(lane.dotGroup, "Assets/gold.png", DOT_SIZE, DOT_SIZE)
  img.xScale = lane.isAI and -1 or 1
  img.x = laneDisplayX(lane, simX)
  img.y = y

  lane.dots[#lane.dots + 1] = { simX = simX, y = y, display = img }
end

-- Coin payoffs queued by updateLane (below): one entry per collected coin,
-- holding the lane that collected it and the countdown left before the
-- OTHER lane gets its pipe. updateLane can't resolve "the other lane" or
-- spawn into it itself: it's defined before playerLane/aiLane exist as
-- locals, so referencing them directly here would silently resolve as
-- globals instead (the same pitfall AI_LOSS_CHECK_PIPES hit once, see the
-- README). gameLoop ticks these down every frame -- deliberately on the
-- game's own clock rather than via timer.performWithDelay, so a pending
-- pipe freezes along with everything else while the keybind menu is open,
-- and is dropped cleanly when a round resets.
local pendingPipeSpawns = {}

local function flapLane(lane)
  if not lane.alive then return end
  lane.velocityY = FLAP_VY
  lane.bird:play()
  if not lane.isAI then
    audio.play(wingSound)
  end
end

local function updateLane(lane, dt)
  if not lane.alive then return end

  -- gravity only applies to the player; the AI lane's velocity is fully
  -- owned by updateAI's proportional controller (see the note there for why)
  if not lane.isAI then
    lane.velocityY = lane.velocityY + GRAVITY * dt
  end
  lane.bird.y = lane.bird.y + lane.velocityY * dt
  lane.bird.rotation = math.max(-30, math.min(70, lane.velocityY * 0.06))
  if lane.bird.y < CEIL_LIMIT then
    lane.bird.y = CEIL_LIMIT
  end

  if lane.dashCooldownRemaining > 0 then
    lane.dashCooldownRemaining = math.max(0, lane.dashCooldownRemaining - dt)
  end

  -- spend down any pending dash distance at a fixed extra rate so it plays
  -- out over DASH_TRANSITION_TIME as a burst of speed rather than an
  -- instant jump; once dashRemaining hits 0 scrolling just returns to
  -- SCROLL_SPEED, keeping all the ground already gained
  local dashStep = 0
  if lane.dashRemaining > 0 then
    dashStep = math.min(lane.dashRemaining, (DASH_DISTANCE / DASH_TRANSITION_TIME) * dt)
    lane.dashRemaining = lane.dashRemaining - dashStep
  end
  local scrollThisTick = SCROLL_SPEED * dt + dashStep

  local died = false
  if lane.bird.y > GROUND_LIMIT then
    lane.bird.y = GROUND_LIMIT
    died = true
  end

  lane.landSimX = lane.landSimX - scrollThisTick
  if lane.landSimX <= 0 then
    lane.landSimX = lane.landSimX + LANE_W
  end
  lane.land.x = laneDisplayX(lane, lane.landSimX)

  -- walked back-to-front so a pipe can be dropped from the list mid-loop
  for i = #lane.pipes, 1, -1 do
    local p = lane.pipes[i]
    p.simX = p.simX - scrollThisTick

    -- A clamp squeezes shut on its way across. The countdown only runs once
    -- the pipe is actually on screen, so one queued up behind a burst of
    -- coins arrives at the same stage of closing as any other rather than
    -- having quietly shut while it waited off to the right.
    if p.clamping and p.simX <= LANE_W + PIPE_HALF_W and p.clampT < CLAMP.closeTime then
      p.clampT = math.min(CLAMP.closeTime, p.clampT + dt)
      local closed = p.clampT / CLAMP.closeTime
      p.gapHalf = p.gapHalfBase * (1 - closed * (1 - CLAMP.gapMin))
      layoutPipeJaws(p)
    end

    -- Breathers and drifters run on the same on-screen-only clock. A
    -- breather's cosine starts at 1, i.e. wide open, the moment it appears.
    local onScreen = p.simX <= LANE_W + PIPE_HALF_W
    if p.breathing and onScreen then
      p.breathT = p.breathT + dt
      local open = 0.5 + 0.5 * math.cos(p.breathT / BREATHE.period * 2 * math.pi)
      p.gapHalf = p.gapHalfBase * (BREATHE.gapMin + (1 - BREATHE.gapMin) * open)
      layoutPipeJaws(p)
    end
    if p.drifting and onScreen then
      p.driftPhase = p.driftPhase + dt / DRIFT.period * 2 * math.pi
      p.y = p.driftBaseY + math.sin(p.driftPhase) * DRIFT.amp
    end

    if not died and (not p.scored) and p.simX < BIRD_LOCAL_X then
      p.scored = true
      lane.score = lane.score + 1
      lane.scoreText.text = tostring(lane.score)
      if not lane.isAI then
        audio.play(pointSound)
      end

      if lane.isAI and lane.score % AI_LOSS_CHECK_PIPES == 0 then
        local lossChance = AI_LOSS_CHANCE_MIN + math.random() * (AI_LOSS_CHANCE_MAX - AI_LOSS_CHANCE_MIN)
        if math.random() < lossChance then
          died = true
        end
      end
    end

    if p.simX < -p.halfW - 14 then
      -- nothing recycles any more: once a pipe is off the left edge it's
      -- gone for good, until the other lane earns this one another
      p:removeSelf()
      table.remove(lane.pipes, i)
    else
      p.x = laneDisplayX(lane, p.simX)

      if not died and laneCollides(lane, p) then
        died = true
      end
    end
  end

  for i = #lane.dots, 1, -1 do
    local d = lane.dots[i]
    d.simX = d.simX - scrollThisTick
    d.display.x = laneDisplayX(lane, d.simX)

    local remove = false
    if d.simX < -60 then
      remove = true -- missed -- scrolled off unclaimed, so no pipe is earned
    elseif not died
      and math.abs(BIRD_LOCAL_X - d.simX) < DOT_HIT_RADIUS
      and math.abs(lane.bird.y - d.y) < DOT_HIT_RADIUS
    then
      -- collecting it neither adds to nor takes from this lane's score; it
      -- queues a pipe for the OTHER lane, COIN_PIPE_DELAY seconds out.
      -- fromSimX/fromY are where the flight animation starts from, captured
      -- here because the coin itself is removed on the next line. The launch
      -- sound is played by beginCoinFlight rather than here, so that it
      -- fires for the AI's pickups too -- being sent a pipe should be as
      -- audible as sending one.
      remove = true
      pendingPipeSpawns[#pendingPipeSpawns + 1] = {
        from = lane,
        remaining = COIN_PIPE_DELAY,
        fromSimX = d.simX,
        fromY = d.y,
      }
    end

    if remove then
      d.display:removeSelf()
      table.remove(lane.dots, i)
    end
  end

  if died then
    lane.alive = false
    lane.bird.rotation = 90
    if not lane.isAI then
      audio.play(hitSound)
    end
  end
end

-- A single flap is a fixed, fairly strong impulse (FLAP_VY) meant for a
-- human tapping irregularly -- worked out on paper (and confirmed with a
-- standalone simulation of this exact physics), one flap swings the bird
-- roughly 60px if uncorrected, which is bigger than the pipe gap's own
-- +/-50px tolerance. That means no amount of clever *timing* of full-power
-- discrete flaps can reliably thread the gap: reactive, predictive, and
-- hysteresis-gated versions were all tried and all failed almost every run
-- in simulation. Instead, the AI flies on a proportional "autopilot" that
-- continuously blends its velocity toward a desired speed proportional to
-- how far it is from the gap center (capped, and eased in over each tick
-- rather than snapping) -- gravity is skipped for this lane in updateLane
-- so this is the sole author of its vertical motion. In 60 simulated
-- matches this reliably ran past 280 pipes (test was capped there) with
-- zero deaths, comfortably past the 5-20 pipe target.
local AI_KP = 4        -- desired speed per pixel of vertical error
local AI_CAP = 300     -- max commanded vertical speed (px/s)
local AI_BLEND = 0.3   -- fraction of the way to desired speed covered per tick
local AI_ANIM_INTERVAL = 0.3 -- just cosmetic: how often to replay the wing flap

-- The autopilot above reacts instantly, which is what made it fly this
-- well in the first place -- but that reads as inhumanly perfect. AI_DELAY_TICKS
-- (declared up with the other constants, since resetLane needs it too) gives
-- it a fixed 100ms reaction lag instead of slowing it down or making it
-- less accurate: each tick's computed correction is queued and only
-- actually applied AI_DELAY_TICKS ticks later, like a human noticing and
-- reacting to the gap slightly after the fact rather than an AI reading
-- the game state instantly.

-- On top of the lag, the target itself rides a slow sine wave instead of
-- sitting still, so the AI visibly bobs up and down in flight rather than
-- gliding to a dead stop on the gap's exact center -- closer to how a
-- human's altitude wanders a bit even while roughly tracking the gap.
-- Amplitude was found by simulation: 28-38px all survived 300/300 trials
-- with zero deaths, while 45px started killing it almost every run, so
-- 32px keeps a comfortable margin below that cliff.
local AI_BOB_AMPLITUDE = 32
-- That 32 was measured against a 50px half-opening. Shaped tips and clamps
-- both leave less than that, so the amplitude is held to the same share of
-- whatever the pipe actually leaves open rather than to the raw number --
-- which also means it tracks pipe_gap_half_height if that is retuned.
local AI_BOB_GAP_RATIO = AI_BOB_AMPLITUDE / GAP_HALF_H
local AI_BOB_SPEED = 3.5 -- radians/sec, ~1.8s per full bob cycle

local function updateAI(lane, dt)
  if not lane.alive then return end

  -- may find nothing at all: the lane is empty whenever the player hasn't
  -- fed it a pipe lately, in which case the autopilot just holds the
  -- resting altitude below
  local target, bestDist = nil, math.huge
  for _, p in ipairs(lane.pipes) do
    local dist = p.simX - BIRD_LOCAL_X
    if dist > -p.halfW and dist < bestDist then
      bestDist = dist
      target = p
    end
  end

  lane.aiBobPhase = lane.aiBobPhase + AI_BOB_SPEED * dt
  -- Wandering 32px inside an opening only 30px from centre to edge is a
  -- guaranteed crash, so the wander is sized off the tightest point of the
  -- pipe being flown at -- a triangle's point, or a clamp at whatever it has
  -- closed to this tick -- and not off the old fixed number.
  local aimY, aimHalf = LANE_H * 0.42, GAP_HALF_H
  if target then aimY, aimHalf = pipeAim(target) end
  -- A breather comes round to its tightest every period, and sizing the
  -- wander off how open it is *this* tick leaves the bird out near the edge
  -- when the jaws come back in -- the harness lost the AI to breathers that
  -- way more than to anything else. So it wanders only as far as the
  -- tightest breath allows.
  if target and target.breathing then
    aimHalf = math.min(aimHalf, target.gapHalfBase * BREATHE.gapMin)
  end
  local amplitude = math.min(AI_BOB_AMPLITUDE, aimHalf * AI_BOB_GAP_RATIO)
  local bob = math.sin(lane.aiBobPhase) * amplitude
  local targetY = aimY + bob

  -- Feed forward how fast the aim point itself is moving. The controller
  -- only pushes in proportion to how far off it is, so against a drifting
  -- column it settles into trailing it -- about 18px behind at full drift
  -- speed, which on top of the bob was enough to put it into a jaw. Only
  -- counted while it is still the same pipe, or switching to the next one
  -- would read as one enormous tick of motion.
  local aimV = 0
  if target and target == lane.aiLastTarget then
    aimV = (aimY - lane.aiLastAimY) / dt
  end
  lane.aiLastTarget, lane.aiLastAimY = target, aimY

  local error = targetY - lane.bird.y
  local desiredV = math.max(-AI_CAP, math.min(AI_CAP, error * AI_KP + aimV))

  table.insert(lane.aiDelayQueue, desiredV)
  local delayedV = table.remove(lane.aiDelayQueue, 1)

  lane.velocityY = lane.velocityY + (delayedV - lane.velocityY) * AI_BLEND

  lane.aiCooldown = lane.aiCooldown - dt
  if lane.aiCooldown <= 0 then
    lane.bird:play()
    lane.aiCooldown = AI_ANIM_INTERVAL
  end
end

