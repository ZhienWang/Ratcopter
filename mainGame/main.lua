local dieSound, hitSound, pointSound, swooshingSound, wingSound, boomSound

-- The coin-launch sound gets a channel to itself. Every other audio.play in
-- this file auto-allocates a channel, and reserving channel 1 keeps those
-- allocations away from it -- which buys two things: the softer volume set
-- here applies to the coin alone instead of bleeding into the flap/point/hit
-- effects, and every pickup can retrigger this one channel so the sound
-- repeats on each coin earned rather than the second one landing on top of
-- a copy still playing.
local COIN_SOUND_CHANNEL = 1
local COIN_SOUND_VOLUME = 0.3 -- against 1.0 for everything else

local function loadSounds()
  dieSound = audio.loadSound("Sounds/sfx_die.caf")
  hitSound = audio.loadSound("Sounds/sfx_hit.caf")
  pointSound = audio.loadSound("Sounds/sfx_point.aif")
  swooshingSound = audio.loadSound("Sounds/sfx_swooshing.caf")
  wingSound = audio.loadSound("Sounds/sfx_wing.caf")
  boomSound = audio.loadSound("Sounds/sfx_boom.mp3")

  audio.reserveChannels(COIN_SOUND_CHANNEL)
  audio.setVolume(COIN_SOUND_VOLUME, { channel = COIN_SOUND_CHANNEL })
end

-- Plays the coin-launch sound, restarting it if it's still going. audio.play
-- on a busy channel is refused rather than queued, so without the stop a coin
-- earned while the previous one is still sounding would be silent -- and at
-- the current spawn rate two pickups inside one sound's length is common.
local function playCoinSound()
  audio.stop(COIN_SOUND_CHANNEL)
  audio.play(boomSound, { channel = COIN_SOUND_CHANNEL })
end

