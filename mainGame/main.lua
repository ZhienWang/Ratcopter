-- ============================================================
-- Ratcopter: Sewer Race
-- Two side-by-side lanes (you on the left, an AI companion on the
-- right with horizontally-flipped artwork). Neither lane spawns pipes on
-- its own: every pipe on your screen was earned by the AI collecting a
-- coin, and every pipe on the AI's screen was earned by you.
-- The match is 5 rounds; whoever has the higher accumulated
-- score after round 5 wins.
-- ============================================================

-- Everything below runs inside main(), deferred by one frame via
-- timer.performWithDelay(1, main) at the bottom of this file. On HTML5,
-- display.actualContentWidth/Height (and screenOriginX/Y) can still reflect
-- a transient pre-layout value on the very first frame the Lua chunk
-- executes, before the browser/canvas has settled on its final size; a
-- Solar2D forum PSA on zoomEven + HTML5 resize specifically flags this.
-- Building the whole layout one frame later reads the settled values
-- instead, so the game actually fills the real window instead of being
-- shrink-wrapped to whatever size was reported a frame too early.
