-- ---------- Game settings (externalized to gameSetting.csv so the pipe
-- gap formula, the pipe-to-pipe spacing and the coin rate can all be tuned
-- without touching code) ----------
-- Sits up here, above every constant that reads it, because the coin spawn
-- rate just below is now the first of them.
-- File format is "setting,value" rows (a header row is skipped since it
-- doesn't parse as a number). A missing file or a missing individual key
-- falls back to the hardcoded default at its own call site, so a malformed
-- CSV can't break the build.
local function loadGameSettings()
  local settings = {}
  local path = system.pathForFile("gameSetting.csv", system.ResourceDirectory)
  local file = path and io.open(path, "r")
  if file then
    for line in file:lines() do
      local key, value = line:match("^%s*([%a_][%w_]*)%s*,%s*(-?[%d%.]+)%s*$")
      if key then
        settings[key] = tonumber(value)
      end
    end
    io.close(file)
  end
  return settings
end

local gameSettings = loadGameSettings()
local function settingOrDefault(key, default)
  local v = gameSettings[key]
  if v == nil then return default end
  return v
end

-- ---------- Coins ----------
-- A pickup that scrolls in from the right exactly like a pipe. Touching one
-- neither gains nor costs the collector any points -- it's an attack
-- instead: COIN_PIPE_DELAY seconds later, one pipe is generated in the
-- OTHER lane (the player collecting a coin puts a pipe on the AI's screen,
-- and vice versa). Since pipes never spawn on their own any more (see
-- "On-demand pipes" below), coins are the only thing that puts an obstacle
-- on either screen. A coin that scrolls past untouched just fizzles.
local DOT_SIZE = 22 * LANE_SCALE
local DOT_HIT_RADIUS = 22 * LANE_SCALE -- generous relative to DOT_SIZE/2 since it's a small target flown past at speed
-- The wait before each coin is rolled uniformly between these two, both
-- tunable in gameSetting.csv. The defaults are the original 3.5-7.0s window
-- divided by 5: with pipes now coming only from coins, the original rate
-- left both lanes near-empty, and even 3x was sparse enough that a round
-- could end 0-0 with barely a pipe to clear.
local DOT_SPAWN_MIN_INTERVAL = settingOrDefault("coin_spawn_interval_min", 0.7)
-- Clamped up to the min rather than trusted as-is: a max below it would
-- make rollNextDotSpawnIn return negative waits and spawn a coin every
-- single tick, which is a silent flood rather than the loud startup error a
-- bad gap_roll_min/max pair produces.
local DOT_SPAWN_MAX_INTERVAL = math.max(DOT_SPAWN_MIN_INTERVAL,
  settingOrDefault("coin_spawn_interval_max", 1.4))
-- How long after a coin is collected the opposing lane's pipe shows up.
-- This doubles as the flight time of the animation below, so the coin lands
-- exactly as the pipe it earned scrolls in.
local COIN_PIPE_DELAY = 1.0 -- seconds

-- The collected coin doesn't just vanish: it's knocked out of its lane and
-- bounces across to the right edge of the OTHER lane -- the point that
-- lane's pipes scroll in from -- so a player can see an obstacle coming and
-- who sent it, the way a Tetris garbage line telegraphs itself before it
-- lands. Both directions animate: your pickup flies right into the AI's
