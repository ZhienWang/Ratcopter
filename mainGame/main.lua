-- ---------- Pipe jaw geometry ----------
-- These mirror constants of the same name in tools/make_pipe_shapes.py. They
-- describe art that is already generated, so changing one here without
-- re-running that script puts the hitbox out of step with the picture --
-- unlike the gameSetting.csv values further down, which are read fresh every
-- launch and are safe to tune on their own.
--
-- They are one table rather than three bare locals on purpose: every line of
-- this file lives inside main(), and Lua allows a single function only 200
-- locals. The settings tables further down are grouped for the same reason.
local JAW = {
  -- How tall each jaw image is drawn. It has to outrun the lane from any gap
  -- height (the furthest a jaw ever reaches is about 470px), with room to
  -- spare for a clamp closing on top of that.
  h = 560,
  -- How far past the flat gap edge a shaped tip reaches at its deepest.
  notch = 20,
  -- The pipe art only paints the middle 63% of its own width -- the rest is
  -- transparent margin, and has been since these images were first drawn.
  -- Shape profiles run across that painted body rather than the full hitbox,
  -- so a triangle tapers to a point at the edge of the pipe you can see.
  artHalf = 0.63,
}

-- Shapes, and how deeply each bites into the opening as a fraction of
-- JAW.notch. The wider the tight stretch a shape creates, the shallower it is
-- allowed to bite: a triangle pinches only at the exact centre so it can take
-- the full notch, while a pentagon holds its tight band across the middle 45%
-- and would be brutal at the same depth. Teeth are three small triangles
-- side by side: no deeper than a triangle's point, just three of them to line
-- up with, so they give up a little depth for it.
--
-- Triangle and half-moon tips used to be in this list too. They are ground
-- obstacles now (GROUND, below) -- a brick pyramid and a hump, far wider than
-- a pipe -- and their depths stay here only because the generator's notch
-- profile still describes them.
local SHAPES = {
  list = { "straight", "pentagon", "teeth" },
  depth = { straight = 0, triangle = 1.0, halfmoon = 0.8, pentagon = 0.65, teeth = 0.85 },
  teeth = 3, -- mirrors TEETH in the generator
  -- chance is filled in with the rest of the gameSetting.csv values below,
  -- which are not readable this early in the file
}

-- Depth in px that `shape`'s tip reaches past the flat edge, at -1 <= u <= 1
-- across the painted body. Mirrors notch_at() in the generator script; the
-- two have to agree or the art stops matching what kills you.
local function shapeNotchPx(shape, u)
  local depth = (SHAPES.depth[shape] or 0) * JAW.notch
  if depth <= 0 then return 0 end
  local a = math.abs(u)
  if a >= 1 then return 0 end
  if shape == "triangle" then
    return depth * (1 - a)
  elseif shape == "halfmoon" then
    return depth * math.sqrt(math.max(0, 1 - a * a))
  elseif shape == "pentagon" then
    local flat = 0.45
    if a <= flat then return depth end
    return depth * (1 - (a - flat) / (1 - flat))
  elseif shape == "teeth" then
    -- A sawtooth across -1..1, taken on u rather than a so an odd number of
    -- teeth puts the middle one's point at u = 0, where pipeAim reads the
    -- tightest spot from.
    local t = (u + 1) * SHAPES.teeth / 2
    local f = t - math.floor(t)
    return depth * (1 - math.abs(2 * f - 1))
  end
  return 0
end

-- ---------- Ground obstacles ----------
-- A column's bottom half can be something standing on the ground instead of
-- a pipe: a stepped brick pyramid or a rounded hump. They are much wider than
-- a pipe and are not pipes at all, so they get their own art and their own
-- hitbox rather than a notch cut into a jaw. The art is generated by
-- tools/make_ground_obstacles.py; every number in `pyramid` and `humps`
-- mirrors a constant there and has to agree with it, exactly as JAW does
-- with the pipe generator.
--
-- Sizes are in lane pixels on both axes -- unlike pipes they are not
-- stretched by LANE_SCALE, since bricks drawn at one size and shown at
-- another would stop being square to the grid.
local GROUND = {
  kinds = { "pyramid", "hump" },
  -- Where both stand: a few pixels down into the top of the ground art, so
  -- they read as planted on it rather than hovering on its edge.
  baseY = LAND_TOP + 5,
  -- A pyramid is `rows` courses of bricks, one brick narrower (half a brick
  -- in from each side) per course, with a single brick on top.
  pyramid = { brickW = 28, brickH = 18, rows = { 3, 4, 5, 6 } },
  -- A hump is half an ellipse, w wide and h tall.
  humps = { { w = 150, h = 56 }, { w = 190, h = 74 }, { w = 230, h = 92 } },
  -- How much of the column's usual opening is left between the pipe hanging
  -- above and the obstacle's highest point, as a fraction of it. Set by
  -- simulation so each is about as hard to get past as the narrow pipe tip
  -- it replaced (see the README entry for 2026-09-28).
  open = { pyramid = 0.85, hump = 0.83 },
  -- chance is read from gameSetting.csv further down, with the others
}

-- Height, width and art for one obstacle of `kind` at size index `size`.
GROUND.dims = function(kind, size)
  if kind == "pyramid" then
    local rows = GROUND.pyramid.rows[size]
    return rows * GROUND.pyramid.brickH, rows * GROUND.pyramid.brickW
  end
  local h = GROUND.humps[size]
  return h.h, h.w
end

GROUND.image = function(kind, size, themeKey)
  return "Assets/" .. kind .. "_" .. themeKey .. "_" .. size .. ".png"
end

-- y of the obstacle's surface `dx` pixels either side of its centre, or nil
-- where there is no obstacle at all. This is what kills you, and it is the
-- same outline the art is drawn to.
GROUND.surfaceAt = function(kind, size, dx)
  local a = math.abs(dx)
  if kind == "pyramid" then
    local py = GROUND.pyramid
    local rows = py.rows[size]
    -- course k (0 at the bottom) spans (rows - k) bricks, so the courses
    -- still under this point are those with (rows - k) * brickW / 2 > a
    local courses = math.min(rows, math.ceil(rows - 2 * a / py.brickW))
    if courses <= 0 then return nil end
    return GROUND.baseY - courses * py.brickH
  end
  local h = GROUND.humps[size]
  local r = a / (h.w / 2)
  if r >= 1 then return nil end
  return GROUND.baseY - h.h * math.sqrt(1 - r * r)
end
