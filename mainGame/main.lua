-- ---------- Coin flight (the cross-lane "sent garbage") ----------
-- Each lane's frame is a display.newContainer, which clips its contents, so
-- a coin travelling between lanes cannot live in either lane's group -- it
-- would be cut off at the lane edge. Flights ride in this top-level group
-- instead, created here so it sits directly above both lane frames and the
-- divider, and below every HUD element built further down.
local coinFlightGroup = display.newGroup()

-- Lane-local coordinates out to screen coordinates. A lane frame is centered
-- on screen and its content group is offset by half the lane, which works out
-- to the lane's left edge plus the local x.
local function laneScreenX(lane, localX)
  local laneLeft = lane.isAI
    and (SCREEN_LEFT + display.actualContentWidth - LANE_W)
    or SCREEN_LEFT
  return laneLeft + localX
end

local function laneScreenY(localY)
  return SCREEN_TOP + localY
end

-- Starts the visual for one queued payoff: a coin lifted out of the lane
-- that collected it, at the exact spot it was taken, aimed at the ground at
-- the far right edge of the opposing lane.
local function beginCoinFlight(pending)
  local target = otherLane(pending.from)
  local img = display.newImageRect(coinFlightGroup, "Assets/gold.png", DOT_SIZE, DOT_SIZE)
  pending.flight = {
    display = img,
    x0 = laneScreenX(pending.from, pending.fromSimX),
    y0 = laneScreenY(pending.fromY),
    x1 = laneScreenX(target, LANE_W),
    y1 = laneScreenY(LAND_TOP),
  }
  img.x, img.y = pending.flight.x0, pending.flight.y0
  playCoinSound()
end

-- Advances a flight to `t` -- 0 at the pickup, 1 as the pipe lands. x is a
-- straight run across; y falls toward the ground line while a decaying |sin|
-- lifts it into COIN_FLIGHT_HOPS successively smaller arcs, so it reads as a
-- coin skipping across the screen rather than gliding over it. Both ends are
-- exact: the arc term is zero at t=0 and t=1, leaving y0 and y1 untouched.
local function updateCoinFlight(flight, t)
  local arc = math.abs(math.sin(t * math.pi * COIN_FLIGHT_HOPS)) * COIN_FLIGHT_HOP_HEIGHT * (1 - t)
  flight.display.x = flight.x0 + (flight.x1 - flight.x0) * t
  flight.display.y = flight.y0 + (flight.y1 - flight.y0) * t - arc
  flight.display.rotation = t * 360 * COIN_FLIGHT_SPINS
end

local function endCoinFlight(pending)
  if pending.flight then
    pending.flight.display:removeSelf()
    pending.flight = nil
  end
end

-- Drops every queued payoff along with its coin, so a flight left over from
-- the previous round can't land into a lane that has since been rebuilt or
-- leave its coin stranded mid-screen.
local function clearPendingPipeSpawns()
  for _, pending in ipairs(pendingPipeSpawns) do
    endCoinFlight(pending)
  end
  pendingPipeSpawns = {}
end

