-- The "spectating" phase and its banner are gone: under the elimination rule
-- a round ends the instant either bird goes down, so there is never an AI run
-- left to watch after the player crashes.
local function refreshOverlay()
  if match.phase == "playing" then
    setOverlayVisible(false)
    return
  end

  setOverlayVisible(true)

  if match.phase == "ready" then
    overlayTitle.text = "ROUND " .. match.round .. " / " .. TOTAL_ROUNDS
    overlaySubtitle.text = "TAP, CLICK, OR PRESS SPACE TO START"
  elseif match.phase == "roundover" then
    -- the headline is who went down, since that -- not the score -- is what
    -- ended the round
    if match.eliminated == "both" then
      overlayTitle.text = "BOTH ELIMINATED"
    elseif match.eliminated == "you" then
      overlayTitle.text = "YOU WERE ELIMINATED"
    else
      overlayTitle.text = "AI ELIMINATED"
    end
    overlaySubtitle.text = "ROUND " .. match.round .. "   -   YOU " .. playerLane.score .. "  -  AI " .. aiLane.score .. "     (tap for round " .. (match.round + 1) .. ")"
  elseif match.phase == "matchover" then
    local verdict
    if match.playerTotal > match.aiTotal then
      verdict = "YOU WIN THE RACE!"
    elseif match.aiTotal > match.playerTotal then
      verdict = "AI WINS THE RACE!"
    else
      verdict = "IT'S A TIE!"
    end
    overlayTitle.text = verdict
    overlaySubtitle.text = "TOTAL  YOU " .. match.playerTotal .. "  -  AI " .. match.aiTotal .. "   (best " .. match.bestTotal .. ")  -  tap to play again"
  end
end
