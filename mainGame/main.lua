local COIN_FLIGHT_HOPS = 3 -- arcs traced on the way across
local COIN_FLIGHT_HOP_HEIGHT = 80 * LANE_SCALE
local COIN_FLIGHT_SPINS = 2 -- full rotations over the trip

-- Original formula was the literal expression "100 + 20 * math.random(1, 10)"
-- (gaps land on 120, 140, ... 300); each piece is now its own tunable value.
-- ---------- Opening size, shapes and clamps (gameSetting.csv) ----------
-- Half the height of a pipe's opening, before any shape bites into it. Was a
-- hardcoded 50 and is now the reference every other number here is measured
-- against, including the AI's bob.
local GAP_HALF_H = settingOrDefault("pipe_gap_half_height", 50)

-- Chance a pipe gets a shaped tip (triangle/half-moon/pentagon) rather than
-- the flat one pipes have always had. 0 restores the old game exactly.
SHAPES.chance = settingOrDefault("pipe_shaped_chance", 0.35)

-- Chance a column's bottom half is a ground obstacle (pyramid or hump) rather
-- than a pipe. Rolled for any column with something on the bottom that did
-- not become a clamp or a breather, including the one-piece columns of the
-- opening era. The 0.25 default is about the share of columns the triangle
-- and half-moon tips took between them when they were pipe shapes (0.55 of
-- columns shaped, two shapes out of four), and pipe_shaped_chance came down
-- to match, so the two remaining tips turn up about as often as before.
GROUND.chance = settingOrDefault("ground_obstacle_chance", 0.25)

-- Chance a pipe is a clamp instead: flat jaws that squeeze shut as it comes
-- at you. Rolled before the shape roll, and a clamp always keeps flat jaws --
-- a shaped tip on a closing opening stacks two narrowings and can leave
-- nothing to fly through.
local CLAMP = {}
CLAMP.chance = settingOrDefault("clamp_pipe_chance", 0.18)

-- Seconds a clamp takes to close the whole way, counted only while it is on
-- screen so a pipe queued far off to the right does not arrive already shut.
-- The budget it has to fit inside: a pipe is visible for about 3.6s, and
-- reaches the bird about 2.1s in. 2.5s therefore closes slowly and visibly
-- the whole way across, and is about 85% shut at the moment you have to fly
-- through it. Set it past 3.6 and the pipe leaves the lane still closing, so
-- clamp_gap_min stops being reachable at all. Floored well clear of zero: at
-- 0 the division below would blow up.
CLAMP.closeTime = math.max(0.25, settingOrDefault("clamp_close_time", 2.5))

-- What a fully closed clamp leaves open, as a fraction of GAP_HALF_H. Held
-- inside 0.2..1 so a bad value cannot produce a pipe with no opening at all
-- (or one that closes into a wider gap than it started with).
CLAMP.gapMin = math.max(0.2, math.min(1, settingOrDefault("clamp_gap_min", 0.45)))

-- A breather is a clamp that does not stay shut: its flat jaws close and
-- reopen on a steady rhythm the whole way across, so the question is when to
-- go through rather than whether there is room. Rolled only for a two-jaw
-- column that did not become a clamp, and keeps flat jaws for the same reason
-- a clamp does. It is always wide open on the frame it comes on screen, so
-- the first thing you see of one is the gap at its widest.
local BREATHE = {}
BREATHE.chance = settingOrDefault("breathe_pipe_chance", 0.12)
-- Seconds for one full close-and-reopen. Floored so the jaws cannot strobe.
BREATHE.period = math.max(0.5, settingOrDefault("breathe_period", 1.6))
-- How far it closes at the tightest point of each breath, as a fraction of
-- GAP_HALF_H. Looser than CLAMP.gapMin by default: a breather's squeeze
-- comes round again every period, so it is met far more often than a
-- clamp's single close.
BREATHE.gapMin = math.max(0.2, math.min(1, settingOrDefault("breathe_gap_min", 0.55)))

-- A drifting column slides slowly up and down as it comes, jaws and opening
-- together, so the height you lined up for is not quite the height you
-- arrive at. It can be any column -- one jaw or two, flat or shaped -- except
-- a clamp or a breather, since a moving opening that is also changing size
-- asks two things of you at once. The drift starts at a random point in its
-- swing and, like a clamp, only advances while the pipe is on screen.
local DRIFT = {}
DRIFT.chance = settingOrDefault("drift_pipe_chance", 0.2)
-- Pixels either side of where the column was placed. Held under
-- GAP_HALF_H: the most a column is ever placed away from the edge of where
-- gaps can go is less than that, so this keeps a drifting opening from
-- sliding into the ceiling or the floor.
DRIFT.amp = math.max(0, math.min(GAP_HALF_H, settingOrDefault("drift_amplitude", 35)))
-- Seconds for one full swing down and back. Floored for the same reason as
-- a breather's period.
DRIFT.period = math.max(0.5, settingOrDefault("drift_period", 3.0))

-- ---------- Difficulty ramp over a round (gameSetting.csv) ----------
-- A round opens gently and works up. Three eras, on a clock that restarts
-- from zero every round:
--   0..ramp_single_pipe_until  every column carries ONE jaw, hanging from
--                              the ceiling or standing off the floor, with
--                              open lane above or below it to fly round
--   ..ramp_two_pipe_by         columns gradually start arriving with both
--                              jaws -- a real gap -- mixed in with singles
--   ramp_tighten_at..by        that gap closes from wide down to tight
-- Note the whole curve is per round, so the later eras only turn up in a run
-- that actually lasts that long: at ramp_tighten_at = 120 you have to stay
-- alive two minutes on one life to see the gaps tighten.
local RAMP = {
  singleUntil = settingOrDefault("ramp_single_pipe_until", 30),
  twoBy = settingOrDefault("ramp_two_pipe_by", 90),
  tightenAt = settingOrDefault("ramp_tighten_at", 120),
  tightenBy = settingOrDefault("ramp_tighten_by", 180),
  gapWide = settingOrDefault("ramp_gap_wide", 1.35),
  gapTight = settingOrDefault("ramp_gap_tight", 0.85),
}
-- Keep each era ending after it starts, whatever the file asks for: a
-- backwards pair would make rampLerp divide by a negative span.
RAMP.twoBy = math.max(RAMP.singleUntil + 1, RAMP.twoBy)
RAMP.tightenBy = math.max(RAMP.tightenAt + 1, RAMP.tightenBy)

-- Seconds into the current round. Reset by onFlapInput when a round starts
-- and advanced by gameLoop; both lanes read the same number, so the two
-- sides always face the same era of the ramp.
local roundElapsed = 0

-- Least open lane a one-jaw column ever leaves, measured from its edge to
-- the ceiling or the floor. Expressed against GAP_HALF_H so it keeps its
-- proportions if the opening is retuned; four times the half-gap is a very
-- forgiving hole, which is the point of the first era.
RAMP.singleOpenMin = GAP_HALF_H * 4

local function rampLerp(t, fromT, toT, fromV, toV)
  if t <= fromT then return fromV end
  if t >= toT then return toV end
  return fromV + (toV - fromV) * ((t - fromT) / (toT - fromT))
end

-- Chance the next column arrives with both jaws rather than just one.
local function twoJawChance()
  return rampLerp(roundElapsed, RAMP.singleUntil, RAMP.twoBy, 0, 1)
end

-- What to multiply the base opening by right now: wide while two-jaw columns
-- are still arriving, closing down to tight once past ramp_tighten_at.
local function rampGapScale()
  return rampLerp(roundElapsed, RAMP.tightenAt, RAMP.tightenBy, RAMP.gapWide, RAMP.gapTight)
end

-- The newer pipe kinds are held back and phased in on the same round clock,
-- so a round works up through them instead of meeting them all from the
-- first column. Each has a window: absent before `from`, then its chance
-- climbs from nothing to the full drift_/breathe_ chance (or, for teeth, to
-- an equal share of the shape roll) by `to`. The defaults slot them into
-- the eras above -- drift across the one-jaw opening, teeth as columns start
-- pairing up, breathers once most columns have both jaws to breathe with.
RAMP.unlocks = {
  drift = { from = settingOrDefault("ramp_drift_from", 10), to = settingOrDefault("ramp_drift_by", 30) },
  teeth = { from = settingOrDefault("ramp_teeth_from", 20), to = settingOrDefault("ramp_teeth_by", 45) },
  breathe = { from = settingOrDefault("ramp_breathe_from", 45), to = settingOrDefault("ramp_breathe_by", 90) },
}
for _, w in pairs(RAMP.unlocks) do
  w.to = math.max(w.from, w.to) -- a backwards window just unlocks all at once at `from`
end

-- 0..1: how far `kind` has been phased in at this point in the round. Kept
-- in RAMP rather than as its own local; see the note on JAW about the
-- 200-local ceiling.
RAMP.unlocked = function(kind)
  local w = RAMP.unlocks[kind]
  if not w then return 1 end
  if w.to <= w.from then return roundElapsed >= w.from and 1 or 0 end
  return rampLerp(roundElapsed, w.from, w.to, 0, 1)
end

local GAP_BASE = settingOrDefault("gap_base", 100)
local GAP_INCREMENT = settingOrDefault("gap_increment", 20)
local GAP_ROLL_MIN = settingOrDefault("gap_roll_min", 1)
local GAP_ROLL_MAX = settingOrDefault("gap_roll_max", 10)

local function randomGapY()
  return GAP_BASE + GAP_INCREMENT * math.random(GAP_ROLL_MIN, GAP_ROLL_MAX)
end

-- ---------- Flip (not mirror) ----------
-- The AI lane's artwork is horizontally flipped (background, land, pipes,
-- and bird each get xScale = -1, applied per-image in buildLaneVisuals),
-- but layout and motion are NOT mirrored: the bird sits at the same
-- BIRD_LOCAL_X within its own lane, and pipes travel the same direction
-- (right to left) at the same lane-local positions on both sides. This
-- function is a passthrough kept only so every position write goes through
-- one place; positions are identical for both lanes, only the pixels of
-- each individual image are flipped.
local function laneDisplayX(lane, simX)
  return simX
end

-- ---------- On-demand pipes ----------
-- Nothing spawns pipes on a timer or rides a pre-built course: a lane stays
-- completely empty until the OPPOSING lane's bird collects a coin, which
-- generates exactly one pipe here COIN_PIPE_DELAY seconds later (queued in
-- updateLane, spawned by gameLoop). The two lanes therefore no longer fly
-- an identical shared course -- each one's obstacles are whatever the other
-- player earned for it -- so pipes are per-lane display objects created and
-- destroyed on demand rather than three recycled slots reading a shared
-- course table.
--
-- The spacing rules are unchanged from when pipes did ride a fixed course:
-- consecutive pipes in a lane are never closer than PIPE_SPACING (the
-- minimum), but every pipe_spacing_interval_min..max pipes one gap gets
-- stretched by a random pipe_spacing_expand_min..max fraction so the rhythm
-- isn't perfectly uniform. Since spawns are now driven by each lane's own
-- coin traffic instead of one shared course, the "pipes to go until the
-- next stretched gap" counter is per-lane state (lane.pipesUntilWideGap)
-- rather than a single shared one.
local PIPE_SPACING_INTERVAL_MIN = settingOrDefault("pipe_spacing_interval_min", 2)
local PIPE_SPACING_INTERVAL_MAX = settingOrDefault("pipe_spacing_interval_max", 7)
local PIPE_SPACING_EXPAND_MIN = settingOrDefault("pipe_spacing_expand_min", 0.20)
local PIPE_SPACING_EXPAND_MAX = settingOrDefault("pipe_spacing_expand_max", 0.30)

local function rollPipesUntilWideGap()
  return math.random(PIPE_SPACING_INTERVAL_MIN, PIPE_SPACING_INTERVAL_MAX)
end

-- Minimum distance to leave between a lane's newest pipe and the one before
-- it. Every rollPipesUntilWideGap()-th call returns a stretched gap instead
-- of the plain minimum; the countdown lives on the lane, so each side's
-- rhythm follows its own pipe count.
local function nextPipeSpacing(lane)
  lane.pipesUntilWideGap = lane.pipesUntilWideGap - 1
  if lane.pipesUntilWideGap <= 0 then
    lane.pipesUntilWideGap = rollPipesUntilWideGap()
    local expandFrac = PIPE_SPACING_EXPAND_MIN + math.random() * (PIPE_SPACING_EXPAND_MAX - PIPE_SPACING_EXPAND_MIN)
    return PIPE_SPACING * (1 + expandFrac)
  end
  return PIPE_SPACING
end

