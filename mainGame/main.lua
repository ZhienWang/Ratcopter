-- Returns true if a dash actually fired, false if it was blocked (menu
-- open, not playing, dead, or still on cooldown) -- callers that need to
-- react only to a real dash (e.g. hold-to-dash deciding whether to swallow
-- the eventual release tap) check this instead of assuming it always fires.
tryDash = function()
  if menuOpen then return false end
  if match.phase ~= "playing" then return false end
  if not playerLane.alive then return false end
  if playerLane.dashCooldownRemaining > 0 then return false end

  -- the world advances under the bird, permanently, instead of the bird
  -- lunging out and snapping back: updateLane spends this down as extra
  -- scroll speed over DASH_TRANSITION_TIME, so it plays out as a quick
  -- burst rather than an instant jump, with nothing given back afterward.
  playerLane.dashRemaining = playerLane.dashRemaining + DASH_DISTANCE
  playerLane.dashCooldownRemaining = DASH_COOLDOWN
  setDashIndicatorReady(false)
  audio.play(swooshingSound)
  spawnDashWind()
  ignoreTapUntil = system.getTimer() + 60
  return true
end

-- Running timer waiting to see if a left click held down for
-- holdDashDelayMs should turn into a dash; cancelled on release (or a
-- fresh press) so a quick click still just flaps as normal.
local holdDashTimer = nil

local function cancelHoldDashTimer()
  if holdDashTimer then
    timer.cancel(holdDashTimer)
    holdDashTimer = nil
  end
end

local function onMouseEvent(event)
  if event.type == "down" and event.isSecondaryButtonDown then
    tryDash()
    return true
  end

  if event.type == "down" and event.isPrimaryButtonDown and not event.isSecondaryButtonDown then
    cancelHoldDashTimer()
    holdDashSuppressTap = false -- as above: don't carry one press's flag into the next
    if holdToDashEnabled and not menuOpen then
      holdDashTimer = timer.performWithDelay(holdDashDelayMs, function()
        holdDashTimer = nil
        if tryDash() then
          holdDashSuppressTap = true
        end
      end)
    end
    return false
  end

  if event.type == "up" then
    cancelHoldDashTimer()
  end
  return false
end
