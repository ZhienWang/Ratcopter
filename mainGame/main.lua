-- above so the tap catcher could be wired up before the theme button) ----------
onFlapInput = function()
  if match.phase == "playing" then
    flapLane(playerLane)
    return
  end

  if match.phase == "matchover" then
    match.round = 1
    match.playerTotal = 0
    match.aiTotal = 0
  elseif match.phase == "roundover" then
    match.round = match.round + 1
  end

  resetLane(playerLane)
  resetLane(aiLane)
  setDashIndicatorReady(true)
  roundElapsed = 0 -- the difficulty ramp starts over with every round
  nextDotSpawnIn = rollNextDotSpawnIn()
  clearPendingPipeSpawns()
  match.phase = "playing"
  audio.play(swooshingSound)
  refreshOverlay()
end

-- Mirrors the mouse's hold-to-dash timer (see onMouseEvent below) but for
-- the flap key: while holdToDashEnabled, pressing it doesn't flap right
-- away -- it waits to see whether the key comes back up before
-- holdDashDelayMs (a tap, so it flaps on "up") or is still down when the
-- timer fires (a hold, so it dashes instead and the eventual "up" is a
-- no-op). flapKeyHeld guards against OS key-repeat re-arming the timer.
local flapKeyHeld = false
local holdDashKeyTimer = nil
local holdDashSuppressFlapKeyUp = false

local function cancelHoldDashKeyTimer()
  if holdDashKeyTimer then
    timer.cancel(holdDashKeyTimer)
    holdDashKeyTimer = nil
  end
end

local function onKeyEvent(event)
  if event.phase == "up" then
    if event.keyName == keyBindings.flap then
      flapKeyHeld = false
      cancelHoldDashKeyTimer()
      local suppressed = holdDashSuppressFlapKeyUp
      holdDashSuppressFlapKeyUp = false
      if not suppressed and not menuOpen and holdToDashEnabled then
        onFlapInput()
      end
      return true
    end
    return false
  end

  if event.phase ~= "down" then return false end

  if listeningForBinding then
    keyBindings[listeningForBinding] = event.keyName
    saveKeyBindings()
    listeningForBinding = nil
    refreshKeybindLabels()
    return true
  end

  if menuOpen then
    return true -- swallow gameplay keys while the menu is open
  end

  if event.keyName == keyBindings.flap then
    if not holdToDashEnabled then
      onFlapInput()
      return true
    end
    if not flapKeyHeld then
      flapKeyHeld = true
      cancelHoldDashKeyTimer()
      holdDashKeyTimer = timer.performWithDelay(holdDashDelayMs, function()
        holdDashKeyTimer = nil
        if tryDash() then
          holdDashSuppressFlapKeyUp = true
        end
      end)
    end
    return true
  end
  if event.keyName == keyBindings.dash1 or event.keyName == keyBindings.dash2 then
    tryDash()
    return true
  end
  return false
end
Runtime:addEventListener("key", onKeyEvent)

