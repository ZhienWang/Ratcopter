-- A handful of thin streak rects near the bird, parented into the player's
-- own lane group so they're clipped to it the same as everything else,
-- kicked backward and faded/stretched out to read as a gust of wind.
local function spawnDashWind()
  local birdScreenX = laneDisplayX(playerLane, BIRD_LOCAL_X)
  local birdY = playerLane.bird.y

  for _ = 1, 7 do
    local streak = display.newRect(
      playerLane.group,
