-- Flashes the indicator a few times right as the cooldown finishes, so the
-- moment the dash becomes available again is obvious rather than just a
-- static color change you might not notice.
local function blinkDashIndicator()
  setDashIndicatorReady(true)
  local blinksLeft = 6
  local function step()
    dashIndicator.alpha = (dashIndicator.alpha < 1) and 1 or 0.15
